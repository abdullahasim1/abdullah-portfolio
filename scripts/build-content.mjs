/** llms-full.txt mein blog section inject karo */
function injectLlmsFullBlog(posts) {
  const llmsPath = path.join(ROOT, "public", "llms-full.txt");
  const existing = fs.readFileSync(llmsPath, "utf8");

  const blogSection = `
## Blog

${posts
  .slice(0, 3)
  .map(
    (p) =>
      `- **${escapeXml(p.title)}** (${new Date(p.date).toLocaleDateString(
        "en-US",
      )}) — ${escapeXml(p.description).substring(0, 150)}...`
  )
  .join("\n")}

---

*Full blog archive at ${SITE_URL}/rss.xml*
`;

  const startMarker = `<!-- LLMS-BLOG:START -->`;
  const endMarker = `<!-- LLMS-BLOG:END -->`;

  if (existing.includes(startMarker) && existing.includes(endMarker)) {
    const re = new RegExp(`${escapeRegex(startMarker)}([\\s\\S]*?)${escapeRegex(endMarker)}`, "m");
    const newContent = existing.replace(re, `${startMarker}\n${blogSection}\n${endMarker}`);
    fs.writeFileSync(llmsPath, newContent);
  } else {
    const newContent = `${existing.trim()}\n${startMarker}\n${blogSection}\n${endMarker}\n`;
    fs.writeFileSync(llmsPath, newContent);
  }
  console.log("llms-full.txt blog section injected");
}

function escapeRegex(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

